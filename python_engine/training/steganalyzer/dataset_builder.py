"""Dataset Builder for CNN Steganalyzer Model (Phase 16).

Creates paired Cover (label 0) vs. Stego (label 1) images for steganalysis training:
- Covers span diverse spatial complexities: flat surfaces, smooth gradients, sinusoidal waves,
  natural textures, high-frequency edges, and pseudo-natural patterns.
- Stegos are generated by applying genuine embedding algorithms (Baseline LSB, Adaptive LSB,
  and PRNG Key-Scattered AI LSB) with varying bit allocation and payload lengths.
- Enforces strict image-level train (70%) / validation (15%) / test (15%) splitting to prevent
  any cross-split data leakage.
- Provides PyTorch Dataset and DataLoader integration for fast training.
"""
import math
import os
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Union

import cv2
import numpy as np
import torch
from torch.utils.data import Dataset

from app.steganography.baseline_lsb import BaselineLSB
from app.steganography.adaptive_rules import AdaptiveRulesLSB
from app.steganography.scatter_stego import KeyScatteredAiLSB


class SteganalysisDataset(Dataset):
    """PyTorch Dataset yielding (tensor, label) pairs for Cover vs. Stego classification."""

    def __init__(
        self,
        images: np.ndarray,
        labels: np.ndarray,
        methods: Optional[List[str]] = None,
        transform=None,
    ):
        """
        Args:
            images: Grayscale images array of shape [N, H, W] uint8 in [0, 255].
            labels: Binary labels array of shape [N] (0 = Cover, 1 = Stego).
            methods: Optional list of stego method names used per sample.
            transform: Optional transform.
        """
        assert len(images) == len(labels), "Images and labels count must match"
        self.images = images
        self.labels = labels
        self.methods = methods or ["Cover" if l == 0 else "Stego" for l in labels]
        self.transform = transform

    def __len__(self) -> int:
        return len(self.images)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        img = self.images[idx]  # [H, W] uint8
        label = float(self.labels[idx])

        # Convert to float32 tensor [1, H, W]
        img_tensor = torch.from_numpy(img).float().unsqueeze(0)  # [1, H, W] in [0, 255]

        if self.transform is not None:
            img_tensor = self.transform(img_tensor)

        label_tensor = torch.tensor([label], dtype=torch.float32)
        return img_tensor, label_tensor


class SteganalysisDataBuilder:
    """Generates synthetic and realistic cover-stego pairs for training the CNN Steganalyzer."""

    def __init__(self, patch_size: int = 64, random_seed: int = 42):
        self.patch_size = patch_size
        self.rng = np.random.RandomState(random_seed)

    def generate_cover_patch(self, pattern_type: int) -> np.ndarray:
        """Synthesizes a 3-channel RGB cover patch with controlled spatial features.

        Args:
            pattern_type: Integer 0 to 5 selecting pattern family:
                0: Flat smooth surface with gentle shading
                1: Smooth diagonal/radial gradients
                2: Multi-frequency sinusoidal interference waves
                3: High-frequency edge grids & checkerboards
                4: Gaussian blurred noise texture
                5: Mixed natural texture (gradient + edge components)

        Returns:
            RGB uint8 array of shape [patch_size, patch_size, 3].
        """
        ps = self.patch_size
        mod = pattern_type % 6

        if mod == 0:
            # Flat smooth with very gentle illumination variation
            base = self.rng.randint(40, 210, size=(1, 1, 3))
            grad_x = np.linspace(-3, 3, ps).reshape(1, ps, 1)
            grad_y = np.linspace(-3, 3, ps).reshape(ps, 1, 1)
            rgb = base + grad_x + grad_y

        elif mod == 1:
            # Smooth diagonal or radial gradient
            c_start = self.rng.randint(30, 100, size=(3,))
            c_end = self.rng.randint(150, 230, size=(3,))
            t = np.linspace(0, 1, ps)
            gx, gy = np.meshgrid(t, t)
            blend = 0.5 * (gx + gy)
            rgb = np.zeros((ps, ps, 3), dtype=np.float32)
            for c in range(3):
                rgb[:, :, c] = c_start[c] + blend * (c_end[c] - c_start[c])

        elif mod == 2:
            # Multi-frequency sinusoidal waves (natural wave/fabric texture)
            freq1 = self.rng.uniform(1.0, 4.0)
            freq2 = self.rng.uniform(2.0, 5.0)
            phase = self.rng.uniform(0, 2 * math.pi)
            x = np.linspace(0, 2 * math.pi, ps)
            xx, yy = np.meshgrid(x, x)
            wave = 0.5 * np.sin(freq1 * xx + phase) + 0.5 * np.cos(freq2 * yy)
            base_val = self.rng.randint(80, 160)
            rgb = np.full((ps, ps, 3), base_val, dtype=np.float32)
            rgb += wave[:, :, np.newaxis] * 40.0

        elif mod == 3:
            # High-frequency edge grids / checkerboards (complex edge boundaries)
            grid_size = self.rng.choice([4, 8, 16])
            grid = (np.indices((ps, ps)).sum(axis=0) // grid_size) % 2
            contrast = self.rng.randint(25, 60)
            base_val = self.rng.randint(60, 180)
            pattern = base_val + (grid.astype(np.float32) - 0.5) * 2 * contrast
            rgb = np.repeat(pattern[:, :, np.newaxis], 3, axis=2)

        elif mod == 4:
            # Blurred random noise (fine natural granular texture)
            noise = self.rng.normal(128, 25, size=(ps, ps, 3))
            kernel_size = self.rng.choice([3, 5])
            rgb = cv2.GaussianBlur(noise.astype(np.float32), (kernel_size, kernel_size), 1.0)

        else:
            # Mixed texture: smooth backdrop with crisp geometric edges
            base = self.rng.randint(50, 200, size=(1, 1, 3)).astype(np.float32)
            rgb = np.tile(base, (ps, ps, 1))
            num_lines = self.rng.randint(2, 5)
            for _ in range(num_lines):
                pt1 = (self.rng.randint(0, ps), self.rng.randint(0, ps))
                pt2 = (self.rng.randint(0, ps), self.rng.randint(0, ps))
                color = tuple(int(c) for c in self.rng.randint(20, 240, size=3))
                thickness = self.rng.randint(1, 3)
                cv2.line(rgb, pt1, pt2, color, thickness)

        rgb = np.clip(rgb, 0, 255).astype(np.uint8)
        return rgb

    def create_stego_counterpart(
        self,
        cover_rgb: np.ndarray,
        method: str = "scatter",
        payload_fraction: float = 0.5,
    ) -> np.ndarray:
        """Embeds a deterministic synthetic payload into cover_rgb to produce a stego patch.

        Args:
            cover_rgb: RGB cover image array [H, W, 3].
            method: 'baseline', 'adaptive', or 'scatter'.
            payload_fraction: Fraction of max capacity to utilize (0.1 to 0.8).

        Returns:
            Stego RGB image array [H, W, 3] uint8.
        """
        ps = cover_rgb.shape[0]
        # Generate random payload bytes of suitable length
        max_bytes = max(8, int((ps * ps * 3 * 0.1) * payload_fraction))
        seed_int = int(self.rng.randint(0, 1000000))
        rng_payload = np.random.RandomState(seed_int)
        payload = rng_payload.bytes(max_bytes)

        try:
            if method == "baseline":
                stego_rgb, _ = BaselineLSB.embed(cover_rgb, payload)
                return stego_rgb

            elif method == "adaptive":
                # Use block_size=16 for adaptive rule
                stego_rgb, _ = AdaptiveRulesLSB.embed(cover_rgb, payload, block_size=16)
                return stego_rgb

            else:  # 'scatter' (PRNG Key-Scattered AI)
                key = f"StegoSecretKey-{seed_int}"
                stego_rgb, _ = KeyScatteredAiLSB.embed(cover_rgb, payload, key, block_size=16)
                return stego_rgb

        except Exception:
            # Fallback to direct baseline LSB if capacity boundary edge case
            try:
                stego_rgb, _ = BaselineLSB.embed(cover_rgb, payload[:8])
                return stego_rgb
            except Exception:
                # Direct flip of 1 LSB bit in pseudo-random pixels if payload packer fails
                stego_rgb = cover_rgb.copy()
                mask = rng_payload.choice([0, 1], size=cover_rgb.shape, p=[0.7, 0.3])
                stego_rgb = (stego_rgb & 0xFE) | (mask & 0x01).astype(np.uint8)
                return stego_rgb

    def build_dataset(
        self,
        num_cover_images: int = 400,
        output_dir: Optional[Union[str, Path]] = None,
    ) -> Dict[str, SteganalysisDataset]:
        """Generates paired Cover and Stego datasets with train/val/test splits.

        Args:
            num_cover_images: Number of distinct cover image scenes to synthesize.
            output_dir: Optional directory to save `.npz` archive.

        Returns:
            Dictionary containing 'train', 'val', and 'test' SteganalysisDataset objects.
        """
        # Split covers into train (70%), val (15%), test (15%)
        n_train = int(num_cover_images * 0.70)
        n_val = int(num_cover_images * 0.15)
        n_test = num_cover_images - n_train - n_val

        splits_spec = [
            ("train", n_train),
            ("val", n_val),
            ("test", n_test),
        ]

        stego_methods = ["baseline", "adaptive", "scatter"]
        datasets = {}

        for split_name, count in splits_spec:
            images_list: List[np.ndarray] = []
            labels_list: List[int] = []
            methods_list: List[str] = []

            for i in range(count):
                pattern_type = i % 6
                cover_rgb = self.generate_cover_patch(pattern_type)
                # Convert cover to grayscale luminance Y = 0.299R + 0.587G + 0.114B
                cover_gray = cv2.cvtColor(cover_rgb, cv2.COLOR_RGB2GRAY)

                # Add Cover (Label 0)
                images_list.append(cover_gray)
                labels_list.append(0)
                methods_list.append("Cover")

                # Choose stego method and embedding density
                method = stego_methods[i % len(stego_methods)]
                payload_frac = float(self.rng.uniform(0.15, 0.75))
                stego_rgb = self.create_stego_counterpart(cover_rgb, method, payload_frac)
                stego_gray = cv2.cvtColor(stego_rgb, cv2.COLOR_RGB2GRAY)

                # Add Stego (Label 1)
                images_list.append(stego_gray)
                labels_list.append(1)
                methods_list.append(method)

            # Shuffle the split
            indices = np.arange(len(images_list))
            self.rng.shuffle(indices)

            shuffled_images = np.array(images_list, dtype=np.uint8)[indices]
            shuffled_labels = np.array(labels_list, dtype=np.int64)[indices]
            shuffled_methods = [methods_list[idx] for idx in indices]

            datasets[split_name] = SteganalysisDataset(
                images=shuffled_images,
                labels=shuffled_labels,
                methods=shuffled_methods,
            )

        if output_dir:
            out_path = Path(output_dir)
            out_path.mkdir(parents=True, exist_ok=True)
            np.savez_compressed(
                out_path / "steganalyzer_dataset.npz",
                train_images=datasets["train"].images,
                train_labels=datasets["train"].labels,
                val_images=datasets["val"].images,
                val_labels=datasets["val"].labels,
                test_images=datasets["test"].images,
                test_labels=datasets["test"].labels,
            )

        return datasets
